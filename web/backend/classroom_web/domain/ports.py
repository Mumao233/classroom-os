"""Persistence boundaries usable without importing SQLAlchemy or FastAPI."""
from typing import Protocol
from datetime import date
from uuid import UUID

from .data import ClassSession, Course, MaterialVersion, Resource, Semester, Tombstone


class CatalogRepository(Protocol):
    def get_semester(self, resource_id: UUID) -> Semester: ...
    def get_course(self, resource_id: UUID) -> Course: ...
    def get_class_session(self, resource_id: UUID) -> ClassSession: ...
    def get_material(self, resource_id: UUID) -> MaterialVersion: ...
    def create_semester(self, name: str, *, academic_year: str | None = None,
                        start_date: date | None = None, end_date: date | None = None) -> Semester: ...
    def create_course(self, semester_id: UUID, name: str, *, language: str = "auto",
                      color_token: str = "blue", icon_key: str = "book",
                      english_name: str | None = None, teacher: str | None = None,
                      room: str | None = None) -> Course: ...
    def create_class_session(self, course_id: UUID, title: str) -> ClassSession: ...
    def update_semester(self, resource_id: UUID, base_revision: int, *, name: str = ...,
                        academic_year: str | None = ..., start_date: date | None = ...,
                        end_date: date | None = ...) -> Semester: ...
    def rename_course(self, resource_id: UUID, base_revision: int, name: str) -> Course: ...
    def move_course(self, resource_id: UUID, base_revision: int, semester_id: UUID) -> Course: ...
    def move_class_session(self, resource_id: UUID, base_revision: int,
                           course_id: UUID) -> ClassSession: ...
    def update_material(self, course_id: UUID, base_revision: int, *, syllabus: str,
                        glossary: list[dict[str, str]], language: str) -> MaterialVersion: ...


class TombstoneRepository(Protocol):
    def get(self, resource: Resource, resource_id: UUID) -> Tombstone | None: ...
    def revoke(self, resource: Resource, resource_id: UUID, base_revision: int,
               ledger_sequence: int, erasure_epoch: int = 1) -> Tombstone: ...
