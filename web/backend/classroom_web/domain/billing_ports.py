"""Transaction-scoped billing port. The caller owns COMMIT and external effects."""
from typing import Protocol
from uuid import UUID

from .billing import ReservationRequest, Usage


class BillingRepository(Protocol):
    def reserve(self, request: ReservationRequest): ...
    def authorize_send(self, reservation_id: UUID, attempt_id: UUID, fence: int, worker: str): ...
    def consume_permit(self, reservation_id: UUID, submission_key: UUID, quantities: dict, fence: int, worker: str): ...
    def release_unsent(self, reservation_id: UUID): ...
    def mark_unknown(self, reservation_id: UUID): ...
    def reconcile(self, reservation_id: UUID, usage: Usage): ...
    def quota(self): ...
