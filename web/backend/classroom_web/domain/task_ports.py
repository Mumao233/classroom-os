"""Execution ports; domain/application code does not import an ORM or SDK."""
from typing import Protocol
from uuid import UUID

from .tasks import Attempt, Claim, Task


class TaskRepository(Protocol):
    def get(self, identity: UUID) -> Task: ...
    def prepare_attempt(self, task_id: UUID, lease_token: int, worker: str) -> Attempt: ...
    def mark_submitting(self, task_id: UUID, attempt_id: UUID, lease_token: int, worker: str): ...
    def store_result(self, task_id: UUID, attempt_id: UUID, raw_output: str): ...
    def publish_result(self, task_id: UUID, attempt_id: UUID, lease_token: int, worker: str) -> Task: ...
    def mark_unknown(self, task_id: UUID, attempt_id: UUID, lease_token: int, worker: str) -> Task: ...
    def recover(self, task_id: UUID, lease_token: int) -> Task: ...


class Scheduler(Protocol):
    def claim(self, worker: str, lease_seconds: int = 30, batch_size: int = 1) -> list[Claim]: ...
    def expired(self, batch_size: int = 100) -> list[Claim]: ...
    def recover_revoked(self, task_id: UUID, lease_token: int) -> bool: ...


class SimulationProvider(Protocol):
    simulation_only: bool
    def submit(self, task: Task, attempt: Attempt) -> str: ...


class LocalResultReconciler(Protocol):
    def run_once(self, batch_size: int = 100) -> int: ...
